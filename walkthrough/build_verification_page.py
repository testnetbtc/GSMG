#!/usr/bin/env python3
"""Generate walkthrough/12_verification.md from live check results.

It runs verify.py, check_ascii.py and check_manifest.py, reads the
reproduction summary, hashes every artifact and result file, and writes the
page. Re-run it after any change:  python3 walkthrough/build_verification_page.py
"""
import datetime, hashlib, json, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
P = lambda *a: os.path.join(ROOT, *a)

def run(*cmd):
    r = subprocess.run([sys.executable, *cmd], cwd=ROOT, capture_output=True, text=True)
    return r.returncode, (r.stdout + r.stderr).strip()

def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()

def table(dirpath, skip=()):
    rows = []
    for dp, _, fn in os.walk(dirpath):
        for f in sorted(fn):
            if f in skip: continue
            p = os.path.join(dp, f)
            rows.append(f"| `{os.path.relpath(p, ROOT)}` | {os.path.getsize(p):,} | `{sha(p)}` |")
    return "\n".join(rows)

def main():
    rc_v, out_v = run("walkthrough/verify.py")
    rc_a, out_a = run("walkthrough/check_ascii.py")
    rc_m, out_m = run("reproduction/scripts/check_manifest.py")
    res = json.load(open(P("reproduction", "results", "reproduction_results.json")))
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    verdict = lambda rc: "PASS" if rc == 0 else "FAIL"

    page = f"""# Verification -- how everything in this walkthrough is checked

Generated by `walkthrough/build_verification_page.py` on {now}.
Previous: [11_clues_index.md](11_clues_index.md)

## 1. The four checks and their current state

| Check | What it does | Result |
|---|---|---|
| `python3 walkthrough/verify.py` | second, independent implementation of every solved step (grid, hashes, the three AES stages, EBCDIC + Beaufort, checkerboard, soup layout, Bifid, prize key, the community openings) plus an audit that every SHA-256 printed in `walkthrough/*.md` is the hash of a held object or a verified value, and that the soup / DBBI / Bifid strings printed in the pages are byte-exact | **{verdict(rc_v)}** -- {out_v.splitlines()[-1]} |
| `python3 reproduction/scripts/reproduce.py` | the archive's own reproduction (Python vs OpenSSL CLI, iconv vs cp273); writes `reproduction/results/` | summary {res['summary']} ({res['generated_utc'][:10]}); a `discrepancy` would mean a mismatch with the prior record -- none |
| `python3 reproduction/scripts/check_manifest.py` | every file under `sources/` is accounted for in the lineage table with a matching hash | **{verdict(rc_m)}** -- {out_m.splitlines()[-1]} |
| `python3 walkthrough/check_ascii.py` | no non-ASCII typography in the archive's documents (`walkthrough/` must be pure 7-bit ASCII) | **{verdict(rc_a)}** -- {out_a.splitlines()[-1]} |

## 2. Hashes of every artifact and result file

SHA-256 of the file bytes as stored in this repository. (For the AES
envelopes the hash of the DECODED envelope, which is what the pages quote,
is checked by `verify.py`; the values below are of the base64 text files.)

### reference/artifacts/

| File | Bytes | SHA-256 |
|---|---:|---|
{table(P("reference", "artifacts"))}

### reproduction/results/

| File | Bytes | SHA-256 |
|---|---:|---|
{table(P("reproduction", "results"), skip=("README.md",))}

## 3. verify.py output

```
{out_v}
```

## 4. check_manifest.py output (tail)

```
{chr(10).join(out_m.splitlines()[-8:])}
```
"""
    open(P("walkthrough", "12_verification.md"), "w").write(page)
    print("wrote walkthrough/12_verification.md;", "verify:", verdict(rc_v), "ascii:", verdict(rc_a), "manifest:", verdict(rc_m))
    sys.exit(0 if rc_v == rc_a == rc_m == 0 else 1)

if __name__ == "__main__":
    main()
