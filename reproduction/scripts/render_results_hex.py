#!/usr/bin/env python3
"""Write a human-readable hex view (<name>.hex) next to every binary output in
reproduction/results/, so the bytes can be inspected on GitHub, where a .bin
file is otherwise shown as mojibake or hidden.

Format: a two-line header (file, size, SHA-256), then `hexdump -C` style rows:
offset, 16 bytes in hex, and the printable-ASCII column ('.' for the rest).
Deterministic; safe to re-run.  Usage: python3 reproduction/scripts/render_results_hex.py
"""
import hashlib, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "reproduction", "results")


def hexview(data: bytes) -> str:
    rows = []
    for off in range(0, len(data), 16):
        chunk = data[off:off + 16]
        hx = " ".join(f"{b:02x}" for b in chunk[:8])
        if len(chunk) > 8:
            hx += "  " + " ".join(f"{b:02x}" for b in chunk[8:])
        asc = "".join(chr(b) if 32 <= b < 127 else "." for b in chunk)
        rows.append(f"{off:08x}  {hx:<48}  |{asc}|")
    rows.append(f"{len(data):08x}")
    return "\n".join(rows) + "\n"


def main():
    for name in sorted(os.listdir(RES)):
        if not name.endswith(".bin"):
            continue
        data = open(os.path.join(RES, name), "rb").read()
        head = (f"# {name}  {len(data)} bytes  sha256 {hashlib.sha256(data).hexdigest()}\n"
                f"# hex view generated by reproduction/scripts/render_results_hex.py\n")
        out = os.path.join(RES, name[:-4] + ".hex")
        open(out, "w").write(head + hexview(data))
        print(f"wrote {os.path.relpath(out, ROOT)}  ({len(data)} bytes)")


if __name__ == "__main__":
    main()
