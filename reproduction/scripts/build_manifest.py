#!/usr/bin/env python3
"""Generate MANIFEST.md (brief section 7) from the build's own records:
sources/REFS.tsv, sources/discussions/*/COUNTS.json, sources/discussions/attachments/ATTACHMENTS.tsv,
sources/discussions/requests.log, reference/data/SOURCE_LINEAGE.csv, VARIANT_GROUPS.csv and the live
output of check_manifest.py (pasted verbatim)."""
import collections, csv, json, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
P = lambda *a: os.path.join(ROOT, *a)
URL = {"A": "https://github.com/puzzlehunt/gsmgio-5btc-puzzle", "B": "https://github.com/Naddiseo/gsmgio-5btc-puzzle",
       "C": "https://github.com/HosterjackAGV/gsmg-5btc-puzzle"}
NAME = {"A": "puzzlehunt", "B": "naddiseo", "C": "hosterjack"}


def git(*a):
    return subprocess.run(["git", "-C", ROOT, *a], capture_output=True, text=True).stdout


def main():
    refs = list(csv.DictReader(open(P("sources", "REFS.tsv")), delimiter="\t"))
    out = ["# MANIFEST -- completeness proof", "",
           "Generated by `reproduction/scripts/build_manifest.py`. It ties the raw archive (`sources/`) to the curated layer (`reference/`). "
           "Every number below is computed from files in this repository.", ""]
    # 1. imports
    out += ["## 1. Imports", "", "| Key | Repo | URL | Branch | HEAD commit | Files at HEAD | Commits reachable | Subtree prefix |", "|---|---|---|---|---|---:|---:|---|"]
    for r in refs:
        if r["note"] == "default":
            out.append(f"| {r['key']} | {r['repo']} | {URL[r['key']]} | {r['ref']} | `{r['head_commit']}` | {r['files_in_tree']} | {r['commits_reachable']} | `sources/{r['repo']}/` |")
    allc = set()
    for r in refs:
        allc |= set(git("rev-list", r["head_commit"]).split())
    out += ["", f"Distinct commit objects reachable from all {len(refs)} advertised source refs: **{len(allc)}**, all present in this repository "
            "(default branches via `git subtree add`, history preserved; every other ref as a tag `archive/<key>/...`). No source has tags.", "",
            "Non-default refs (unique-vs-default-HEAD files imported under `sources/<repo>/_pr<N>/` or `_branches/<name>/`):", "",
            "| Key | Kind | Ref | Head commit | Archive tag | Commits | Files in tree | Files imported |", "|---|---|---|---|---|---:|---:|---:|"]
    for r in refs:
        if r["note"] != "default":
            out.append(f"| {r['key']} | {r['kind']} | {r['ref']} | `{r['head_commit'][:12]}` | `{r['archive_tag']}` | {r['commits_reachable']} | {r['files_in_tree']} | {r['files_imported']} |")
    out += ["", "Prior report frozen commits (`fb92dd15...`, `9e616934...`, `caaa77a8...`) equal the current HEADs: upstream default branches have not moved.", ""]
    # 2. discussions
    att = list(csv.DictReader(open(P("sources", "discussions", "attachments", "ATTACHMENTS.tsv")), delimiter="\t"))
    by = collections.defaultdict(dict)
    for a in att:
        by[a["repo"]][a["url"]] = a["status"]
    out += ["## 2. Discussions", "", "Collected with the GitHub REST API, unauthenticated and paced (request log: `sources/discussions/requests.log`). "
            "Raw JSON per page with response headers: `sources/discussions/<repo>/raw/`. Lossless Markdown per thread: `issues/NNN.md`, `pulls/NNN.md`.", "",
            "| Repo | Issues | PRs | Comments expected (counters) | Comments fetched | Review records | Review comments | Attachments attempted | fetched | 404 / error |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    mism = []
    for k in "ABC":
        c = json.load(open(P("sources", "discussions", NAME[k], "COUNTS.json")))
        st = collections.Counter(by[NAME[k]].values())
        ok = st.get("200", 0)
        out.append(f"| {k} {NAME[k]} | {c['issues']} | {c['pulls']} | {c['comments_expected']} | {c['comments_fetched']} | {c['reviews']} | {c['review_comments']} | {len(by[NAME[k]])} | {ok} | {len(by[NAME[k]]) - ok} |")
        for m in c["mismatches"]:
            mism.append(f"- {k}#{m['number']}: counter {m['counter']}, repository-wide fetch {m['fetched']}, per-issue refetch {m['refetched']}")
    nreq = sum(1 for _ in open(P("sources", "discussions", "requests.log")))
    out += ["", f"API requests logged: {nreq}. Counter mismatches (re-fetched per issue, unchanged):", ""] + mism + [
        "", "Same counts as the prior report for comments (A 606/605, B 36/35, C 2/2), reviews and review comments. A has 103 issues vs 102: the new one is A#116 (2026-10-15).", ""]
    # 3. dedup
    lin = list(csv.DictReader(open(P("reference", "data", "SOURCE_LINEAGE.csv"))))
    groups = collections.defaultdict(list)
    for r in lin:
        groups[r["group_id"]].append(r)
    roles = collections.Counter(r["role"] for r in lin)
    multi = sum(1 for g in groups.values() if len(g) > 1)
    cross = sum(1 for g in groups.values() if len({r["repo"] for r in g if r["repo"] in "ABC"}) > 1)
    var = list(csv.DictReader(open(P("reference", "data", "VARIANT_GROUPS.csv"))))
    vg = {r["variant_group"] for r in var}
    byrepo = collections.Counter(r["repo"] for r in lin)
    out += ["## 3. Deduplication summary", "",
            f"- total files under `sources/`: **{len(lin)}** (A {byrepo['A']}, B {byrepo['B']}, C {byrepo['C']}, discussions {byrepo['D']}, build metadata {byrepo['M']})",
            f"- byte-identical groups: **{len(groups)}** ({multi} with more than one member; {cross} spanning more than one of A/B/C)",
            f"- near-identical variant groups: **{len(vg)}** ({len(var)} member files; diffs in `reference/data/variants/`; every member reviewed for unique facts -- column `unique_fact_review`)",
            f"- unique files (singleton groups): **{sum(1 for g in groups.values() if len(g) == 1)}**",
            f"- roles: canonical **{roles['canonical']}**, duplicate **{roles['duplicate']}**, variant **{roles['variant']}**", "",
            "Canonical choice for byte-identical groups: upstream in fork history first (A > B > C; B is a GitHub fork of A, C vendors B per its NOTICE), "
            "then default branch before PR/branch extras, then earliest first-seen commit date. Puzzle artifacts additionally have one canonical copy in "
            "`reference/artifacts/` (`reference/data/ARTIFACT_FILES.csv`).", ""]
    # 4. coverage check
    chk = subprocess.run([sys.executable, P("reproduction", "scripts", "check_manifest.py")], capture_output=True, text=True)
    out += ["## 4. Coverage check", "", "`python3 reproduction/scripts/check_manifest.py` (output pasted verbatim):", "", "```text", chk.stdout.rstrip(), "```", "",
            "The PASS line is the completeness claim: every file in `sources/` is a canonical lineage row or a duplicate/variant of one, and its bytes match the recorded hash. "
            "The second statistic shows which canonical files are cited by path or issue number from the readable layer; the rest are raw API pages, response headers, "
            "site code and PR working files, carried by the raw archive and their lineage rows (and summarised in `reference/data/extraction/`).", ""]
    # 5. gaps
    gaps = [a for a in att if a["status"] != "200"]
    seen = set()
    out += ["## 5. Known gaps", "", "| What | URL / locator | Error |", "|---|---|---|"]
    for a in gaps:
        if a["url"] in seen:
            continue
        seen.add(a["url"])
        out.append(f"| attachment ({a['repo']}) | {a['url']} (in {a['locator']}) | {a['status']} |")
    out += [
        "| comment hidden from API | " + "; ".join(m[2:] for m in mism) + " | counter exceeds returned comments on both fetches |",
        "| quoted-only comments | A#72 comment 3935458653 quotes a missing 'ZION' text; A#114 comment 6128068004 quotes missing AomDEV comments | originals not returned by the API |",
        "| comment edit history | all threads | REST API returns current text only; earlier wordings unavailable |",
        "| B PR#15 uncommitted primaries | `CREATOR-LOG_transcript_445_messages.md`, Wayback 2023-11-27 / 2026-04-05 SalPhaseIon captures, other hash-listed files in `ARCHIVE-README.md` | listed by hash only in the PR |",
        "| A PR#93 Telegram export | raw `ChatExport` HTML/JSON and attachments (`salphaseion_plain_79.bin`, `Jrk Bgrt Chat History.txt`, ...) | only the derived transcript and a file listing are shipped |",
        "| C research harnesses | `research/` directory and scratch scripts referenced by 108 of 171 attempts | not in any C ref |",
        "| external repos | `jackdevs66/GSMG5_CDuality`, `floflo777/open-crypto-puzzles` | outside the three-repo scope of this build (not fetched) |",
        "| Wayback captures cited by C | 2023-06-01 SalPhaseIon capture (4,592 B) | not held; not refetched |", ""]
    open(P("MANIFEST.md"), "w").write("\n".join(out) + "\n")
    print("MANIFEST.md written;", chk.stdout.strip().splitlines()[-1])


if __name__ == "__main__":
    main()
